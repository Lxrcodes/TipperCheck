-- Managers in the org can read/write invoices
CREATE POLICY "Managers manage org invoices"
  ON invoices
  FOR ALL
  USING (
    org_id IN (
      SELECT org_id FROM users
      WHERE auth_user_id = auth.uid()
        AND 'manager' = ANY(roles)
        AND is_active = true
    )
  )
  WITH CHECK (
    org_id IN (
      SELECT org_id FROM users
      WHERE auth_user_id = auth.uid()
        AND 'manager' = ANY(roles)
        AND is_active = true
    )
  );

CREATE POLICY "Managers manage org invoice items"
