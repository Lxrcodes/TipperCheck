-- ============================================================================
-- invoices
-- ============================================================================
CREATE TABLE IF NOT EXISTS invoices (
  id           uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
  org_id       uuid        NOT NULL REFERENCES organisations(id) ON DELETE CASCADE,
  created_by   uuid        NOT NULL REFERENCES users(id),
  job_id       uuid        REFERENCES jobs(id) ON DELETE SET NULL,

  -- Generated by trigger on INSERT — do not supply from application
  number       text        NOT NULL,    -- e.g. INV-0001

  -- Client details
  client_name    text NOT NULL,
  client_address text,
  client_email   text,

  -- Dates
  issue_date   date NOT NULL DEFAULT CURRENT_DATE,
  due_date     date,

  -- Financials
  vat_enabled  boolean NOT NULL DEFAULT true,
  total_net    numeric(10,2) NOT NULL DEFAULT 0,
  total_vat    numeric(10,2) NOT NULL DEFAULT 0,
  total_gross  numeric(10,2) NOT NULL DEFAULT 0,

  -- Notes
  notes        text,

  -- Status lifecycle: draft → sent → paid (or void at any point)
  status       text NOT NULL DEFAULT 'draft'
    CHECK (status IN ('draft', 'sent', 'paid', 'void')),

  created_at   timestamptz NOT NULL DEFAULT now(),
  updated_at   timestamptz NOT NULL DEFAULT now(),

  UNIQUE (org_id, number)
);

-- Atomically increment org counter and set invoice number
CREATE OR REPLACE FUNCTION generate_invoice_number()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE
  new_seq integer;
BEGIN
  UPDATE organisations
    SET next_invoice_seq = next_invoice_seq + 1
    WHERE id = NEW.org_id
    RETURNING next_invoice_seq INTO new_seq;

  NEW.number := 'INV-' || lpad(new_seq::text, 4, '0');
  RETURN NEW;
END;
$$;

CREATE TRIGGER set_invoice_number
  BEFORE INSERT ON invoices
  FOR EACH ROW
  EXECUTE FUNCTION generate_invoice_number();

CREATE OR REPLACE FUNCTION touch_invoice_updated_at()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$;

CREATE TRIGGER invoices_updated_at
  BEFORE UPDATE ON invoices
  FOR EACH ROW
  EXECUTE FUNCTION touch_invoice_updated_at();

