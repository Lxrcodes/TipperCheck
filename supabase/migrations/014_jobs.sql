-- ============================================================================
-- Helper: integer sequence → 3-letter job code (1=AAA, 2=AAB, … 17576=ZZZ)
-- Used as the job-level identifier in invoice references: AAA-INS-0001
-- ============================================================================
CREATE OR REPLACE FUNCTION seq_to_job_code(seq integer) RETURNS text
LANGUAGE plpgsql IMMUTABLE
AS $$
DECLARE
  n integer := seq - 1;
BEGIN
  IF seq < 1 OR seq > 17576 THEN
    RAISE EXCEPTION 'seq_to_job_code: % is out of range (1–17576)', seq;
  END IF;
  RETURN chr(65 + (n / 676)) || chr(65 + ((n / 26) % 26)) || chr(65 + (n % 26));
END;
$$;

