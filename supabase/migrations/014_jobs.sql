-- Managers: full access to jobs in their org
CREATE POLICY "managers_all_jobs" ON jobs
  FOR ALL TO authenticated
  USING    (org_id = auth_user_org_id() AND auth_user_has_role('manager'))
  WITH CHECK (org_id = auth_user_org_id() AND auth_user_has_role('manager'));

-- Drivers: read jobs assigned to them
CREATE POLICY "drivers_read_own_jobs" ON jobs
  FOR SELECT TO authenticated
  USING (driver_id = auth_user_id());

-- Managers: full access to status history for jobs in their org
CREATE POLICY "managers_all_job_history" ON job_status_history
  FOR ALL TO authenticated
  USING (
    job_id IN (
      SELECT id FROM jobs WHERE org_id = auth_user_org_id()
    )
    AND auth_user_has_role('manager')
  )
  WITH CHECK (
    job_id IN (
      SELECT id FROM jobs WHERE org_id = auth_user_org_id()
    )
    AND auth_user_has_role('manager')
  );

-- Drivers: read status history for their assigned jobs
CREATE POLICY "drivers_read_own_job_history" ON job_status_history
  FOR SELECT TO authenticated
  USING (
    job_id IN (
      SELECT id FROM jobs WHERE driver_id = auth_user_id()
    )
  );
