CREATE TABLE IF NOT EXISTS jobs (
  id         uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
  org_id     uuid        NOT NULL REFERENCES organisations(id) ON DELETE CASCADE,
  vehicle_id uuid        REFERENCES vehicles(id) ON DELETE SET NULL,
  driver_id  uuid        REFERENCES users(id) ON DELETE SET NULL,
  created_by uuid        NOT NULL REFERENCES users(id),

  -- Generated by trigger on INSERT — do not supply from the application
  reference  text        NOT NULL,   -- e.g. JOB-0001
  job_code   text        NOT NULL,   -- e.g. AAA  (used in invoice refs)

  title        text NOT NULL,
  description  text,
  site_address text,

  status text NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending', 'active', 'completed', 'cancelled')),

  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),

  UNIQUE (org_id, reference),
  UNIQUE (org_id, job_code)
);

-- Atomically increment org counter and derive reference + job_code
CREATE OR REPLACE FUNCTION generate_job_identifiers()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE
  new_seq integer;
BEGIN
  UPDATE organisations
    SET next_job_seq = next_job_seq + 1
    WHERE id = NEW.org_id
    RETURNING next_job_seq INTO new_seq;

  NEW.reference := 'JOB-' || lpad(new_seq::text, 4, '0');
  NEW.job_code  := seq_to_job_code(new_seq);
  RETURN NEW;
END;
$$;

CREATE TRIGGER set_job_identifiers
  BEFORE INSERT ON jobs
  FOR EACH ROW
  EXECUTE FUNCTION generate_job_identifiers();

-- Keep updated_at current on every update
CREATE OR REPLACE FUNCTION touch_job_updated_at()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$;

CREATE TRIGGER jobs_updated_at
  BEFORE UPDATE ON jobs
  FOR EACH ROW
  EXECUTE FUNCTION touch_job_updated_at();

-- ============================================================================
-- job_status_history — immutable audit trail (one row per status change)
-- ============================================================================
CREATE TABLE IF NOT EXISTS job_status_history (
  id         uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
  job_id     uuid        NOT NULL REFERENCES jobs(id) ON DELETE CASCADE,
  status     text        NOT NULL,
  note       text,
  changed_by uuid        NOT NULL REFERENCES users(id),
  changed_at timestamptz NOT NULL DEFAULT now()
);

-- Auto-record the initial status when a job is created
CREATE OR REPLACE FUNCTION record_initial_job_status()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
  INSERT INTO job_status_history (job_id, status, changed_by)
  VALUES (NEW.id, NEW.status, NEW.created_by);
  RETURN NEW;
END;
$$;

CREATE TRIGGER jobs_initial_status
  AFTER INSERT ON jobs
  FOR EACH ROW
  EXECUTE FUNCTION record_initial_job_status();

